import { askClaude, extractJson, jsonHandler, bioBlock } from "./_lib/claude.js";
import { SKILLS } from "./_lib/skills.js";

const SYSTEM = `Ты готовишь посты для вкладки «Записи» (Community) канала AI Music Lab. Правила голоса и ограничения канала — в скилле content-youtube ниже. Следуй им точно.

# Скилл: content-youtube

${SKILLS.content_youtube}

---
ЗАДАЧА: 4 коротких поста для «Записей» — строго по одному на каждый из четырёх Shorts. Каждый пост получает свою тему, свой смысл и свою квадратную картинку. Не объединяй четыре темы в один общий анонс.

Порядок постов обязан совпадать с порядком Shorts: пост #1 относится только к Shorts #1, пост #2 — только к Shorts #2 и так далее. Поле sourceIndex содержит индекс Shorts от 0 до 3.

ГЛАВНОЕ: запись должна быть полезной сама по себе, даже если человек не откроет Short. Это не рекламный анонс и не пересказ ролика. Для каждого поста используй структуру:
1. Узнаваемая проблема или конкретный вопрос по теме Shorts.
2. Практический ответ: 2–3 конкретных наблюдения, шага, настройки или критерия из исходного материала.
3. Блок «Как применить»: одно понятное действие, которое читатель может выполнить сразу.
4. Короткий вывод — что изменится после применения.
5. Спокойный переход к соответствующему Short для демонстрации.

Не пиши «в этом видео я рассказал», «вы узнаете», «смотрите до конца» и другие рекламные фразы. Не выдумывай функций, настроек или результатов, которых нет в исходном материале. Каждый пост — 500–900 знаков и отличается от остальных не только формулировкой, но и практической пользой.

В конце каждого поста — отдельной строкой плейсхолдер ссылки на видео: [ссылка на видео] (пользователь вручную заменит его на реальную ссылку после публикации).

Без упоминаний «AI», «нейросеть», без Suno-атрибуции.

ФОРМАТ ОТВЕТА: верни строго JSON без пояснений:
{"posts": [{"sourceIndex": 0, "angle": "краткое название темы (2-4 слова)", "text": "текст поста, заканчивающийся строкой [ссылка на видео]"}]}`;

export default jsonHandler(async (body, usage) => {
  const { topic, script, synopsis, shortsSeries, current, instruction, channelBio } = body;

  // Режим точечной правки одного поста.
  if (current && instruction) {
    const text = await askClaude({ usage,
      system: SYSTEM,
      user: `${bioBlock(channelBio)}Текущий пост (ракурс «${current.angle}»):\n\n${current.text}\n\nПерепиши его с учётом правки: «${instruction}». Сохрани плейсхолдер [ссылка на видео] в конце. Верни JSON с одним элементом в "posts".`,
      maxTokens: 1500,
    });
    return extractJson(text);
  }

  if (!topic && !script && !synopsis && !shortsSeries?.length) throw new Error("Нет тем или готового сценария");
  const seriesBlock = Array.isArray(shortsSeries) && shortsSeries.length
    ? `\n\nЧетыре Shorts (соблюдай соответствие один к одному):\n${shortsSeries.slice(0, 4).map((item, index) => `${index + 1}. Тема: ${item.topic || "—"}\nСценарий: ${item.script || "—"}\nВывод: ${item.payoff || "—"}\nЗаголовки: ${(item.titles || []).join(" | ")}\nОписание: ${item.description || "—"}`).join("\n\n")}`
    : "";
  const text = await askClaude({ usage,
    system: SYSTEM,
    user: `${bioBlock(channelBio)}Общая тема серии: ${topic || "—"}\n\nГотовый материал (единственный источник фактов):\n${script ? script.slice(0, 7000) : "—"}${seriesBlock}\n\nНапиши ровно 4 самостоятельных полезных поста для «Записей»: по одному на каждый Shorts, в том же порядке. В каждом обязательно должны быть конкретный вывод и действие «как применить».`,
    maxTokens: 3200,
  });
  return extractJson(text);
});
